"""Builds the two generated front-end files from their upstream packages.

    python scripts/build_vendor.py lucide-static-0.460.0.tgz unicode-emoji-json-data-by-group.json

Writes captainguild/web/static/js/icons.js with only the icons the dashboard uses, and
captainguild/web/static/vendor/emoji.json with the emoji picker's list. Both upstream licenses are in THIRD_PARTY.md.
"""
